/**
 * event-provenance.js — Classifies DOM event origin and trust provenance.
 *
 * Categories:
 * - 'human-primary': `event.isTrusted === true`, directly initiated by physical human interaction.
 * - 'framework-derived': Untrusted event emitted by frontend framework (React, Vue, Angular, Oracle JET, ADF).
 * - 'flowtrace-generated': Synthetic event dispatched by FlowTrace internal tools, autofill, or test harnesses.
 * - 'unknown': Untrusted event without known origin.
 *
 * Invariant: Events classified as 'flowtrace-generated' must NEVER be recorded as user actions.
 */

export const ProvenanceCategory = {
  HUMAN_PRIMARY: 'human-primary',
  FRAMEWORK_DERIVED: 'framework-derived',
  FLOWTRACE_GENERATED: 'flowtrace-generated',
  UNKNOWN: 'unknown',
};

/**
 * Classifies an incoming Event's provenance.
 *
 * @param {Event} event
 * @returns {string} One of ProvenanceCategory values
 */
export function classifyEventProvenance(event) {
  if (!event) return ProvenanceCategory.UNKNOWN;

  // 1. Explicit FlowTrace internal synthetic event marker
  if (
    event.__flowtrace_internal__ === true ||
    event.detail?.__flowtrace_internal__ === true ||
    (typeof window !== 'undefined' && window.__FLOWTRACE_DISPATCHING_AUTOFILL__ === true)
  ) {
    return ProvenanceCategory.FLOWTRACE_GENERATED;
  }

  // 2. Browser native trusted human event
  if (event.isTrusted === true) {
    return ProvenanceCategory.HUMAN_PRIMARY;
  }

  // 3. Framework-derived synthetic events
  // React synthetic events or framework component custom events
  if (
    event._reactName ||
    event.nativeEvent ||
    (event.type && ['ojBeforeRowEdit', 'ojRowAction', 'ojValueAction', 'adfRowSelect'].includes(event.type))
  ) {
    return ProvenanceCategory.FRAMEWORK_DERIVED;
  }

  // 4. Custom/Untrusted events without internal marker are treated as framework-derived
  // (e.g. React/Vue/ADF dispatchEvent calls)
  return ProvenanceCategory.FRAMEWORK_DERIVED;
}

/**
 * Determines whether an event is safe to record (i.e. not generated by FlowTrace itself).
 *
 * @param {Event} event
 * @returns {boolean}
 */
export function isRecordableEvent(event) {
  return classifyEventProvenance(event) !== ProvenanceCategory.FLOWTRACE_GENERATED;
}
